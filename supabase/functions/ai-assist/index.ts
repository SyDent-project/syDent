/* قراءة آمنة من خرائط المفاتيح المغلقة: المفاتيح تأتي من العميل، والوصول
   المباشر obj[k] يُرجع أعضاء Object.prototype لمفاتيح مثل __proto__ أو
   constructor أو toString — وكلها **truthy** فتمرّ من حارس `!obj[k]`.
   hasOwn يقصر القراءة على المفاتيح المُعرَّفة فعلاً. */
function pick(map: Record<string, string>, key: unknown): string {
  const k = String(key ?? "");
  return Object.prototype.hasOwnProperty.call(map, k) ? map[k] : "";
}
function hasFeature(map: Record<string, unknown>, key: unknown): boolean {
  return Object.prototype.hasOwnProperty.call(map, String(key ?? ""));
}

