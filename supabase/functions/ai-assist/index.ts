/* تعقيم القائمة الواردة من العميل: أسماء حقول فقط، صفر قيم.
   القصّ **قبل** الـmap يحدّ العمل على مدخل معادٍ (مصفوفة ضخمة). */
function sanitizePlaceholders(raw: unknown): string[] {
  return (Array.isArray(raw) ? raw : [])
    .slice(0, 24)
    .map((p: unknown) => String(p || "").trim())
    .filter((p: string) => /^\{[a-z][a-z_]{1,39}\}$/.test(p))   // يبدأ بحرف — يُسقط {__proto__} وأشباهه
    .slice(0, 12);
}
