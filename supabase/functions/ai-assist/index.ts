Deno.serve(async (req: Request): Promise<Response> => {
  // ── CORS preflight ─────────────────────────────────────────────────
  if (req.method === "OPTIONS") return new Response("ok", { headers: CORS });
  if (req.method !== "POST") return json(405, { error: "method_not_allowed" });

  const SUPABASE_URL = Deno.env.get("SUPABASE_URL");
  const SERVICE_ROLE_KEY = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY");
  const ANTHROPIC_API_KEY = Deno.env.get("ANTHROPIC_API_KEY");
  if (!SUPABASE_URL || !SERVICE_ROLE_KEY) return json(500, { error: "function_misconfigured" });
  if (!ANTHROPIC_API_KEY) return json(500, { error: "ai_key_missing" });

  // Privileged client (service role). Never persists a session.
  const admin = createClient(SUPABASE_URL, SERVICE_ROLE_KEY, {
    auth: { autoRefreshToken: false, persistSession: false },
  });

  // ── 1) Authenticate the caller from THEIR session JWT ──────────────
  const authHeader = req.headers.get("Authorization") || "";
  const jwt = authHeader.replace(/^Bearer\s+/i, "").trim();
  if (!jwt) return json(401, { error: "missing_token" });

  let ownerId: string;
  try {
    const { data, error } = await admin.auth.getUser(jwt);
    if (error || !data?.user) return json(401, { error: "invalid_token" });
    ownerId = data.user.id;
  } catch (_e) {
    return json(401, { error: "invalid_token" });
  }

  // ── 2) Parse + validate request ────────────────────────────────────
  let bodyJson: any;
  try { bodyJson = await req.json(); } catch { return json(400, { error: "bad_json" }); }
  const feature = String(bodyJson?.feature || "");
  const input = bodyJson?.input || {};
  if (!hasFeature(SYSTEM_PROMPTS, feature)) return json(400, { error: "unknown_feature" });

  // ── 2.5) بوابة سطح الأدمن — fail-closed حرفياً كـadmin-ops ─────────
  // ميزات ADMIN_FEATURES تُصرَّح بعضوية platform_admins وحدها، وتتخطّى
  // بوابتَي المستأجر (3) و(3.5) لأنهما تخصّان عيادةً وهذا السطح ليس عيادة.
  // أي خطأ هنا يُغلق الباب (500/403) ولا يُفتح — عكس فلسفة fail-open
  // ببوابة الخطة، لأن هذه بوابة تصريح لا بوابة تهيئة.
  const isAdminFeature = hasFeature(ADMIN_FEATURES, feature);
  if (isAdminFeature) {
    try {
      const { data: pa, error: paErr } = await admin
        .from("platform_admins")
        .select("user_id")
        .eq("user_id", ownerId)
        .maybeSingle();
      if (paErr) return json(500, { error: "auth_check_failed" });
      if (!pa) return json(403, { error: "not_platform_admin" });
    } catch (_e) {
      return json(500, { error: "auth_check_failed" });
    }
  }

  // ── 3) Opt-in gate — SERVER-SIDE (never trust the client toggle) ───
  if (!isAdminFeature) {
    try {
      const { data: cs } = await admin
        .from("clinic_settings")
        .select("ai_features_enabled")
        .eq("owner_id", ownerId)
        .maybeSingle();
      if (!cs || cs.ai_features_enabled !== true) return json(403, { error: "ai_not_enabled" });
    } catch (_e) {
      return json(403, { error: "ai_not_enabled" });
    }
  }

  // ── 3.5) Plan gate — SERVER-SIDE defense-in-depth (mirrors SyDentPlan) ──
  // tenant tier: trial_requests.plan → subscription_plans.entitlements.
  // ai_features === false ⇒ block. Fail-open on error (never lock a tenant
  // out over a config glitch — matches the client SyDentPlan philosophy).
  // Per-plan monthly call cap (Migration 132) — read alongside the plan gate,
  // consumed by gate 4 below. null ⇒ legacy fallback MONTHLY_CALL_CAP.
  // Deliberately stays null for: admin features, ai_override=true (the plan
  // fetch is skipped — a gifted override rides the fallback, never unmetered),
  // a missing plan row, and any absent/invalid key (grandfather philosophy).
  let planCallCap: number | null = null;
  if (!isAdminFeature) {
    try {
      const { data: tr } = await admin
        .from("trial_requests")
        .select("plan, ai_override, status")
        .eq("user_id", ownerId)
        .maybeSingle();
      // Migration 110 — per-account admin override (third gate layer).
      //   false → hard OFF for this tenant, even if the plan includes AI
      //   true  → hard ON, skips the plan check entirely
      //   null  → follow the plan (pre-110 behaviour, unchanged)
      // It does NOT bypass the opt-in gate above (privacy) nor the monthly cap
      // below (cost guard) — both stay in force for every tenant.
      // بوابة حالة الحساب — مرآة ensureAccountAccessible (supabase-init.js) حرفياً:
      //   new / rejected / suspended ⇒ 403 account_not_active (لا نداء Anthropic).
      //   صف مفقود أو حالة مجهولة ⇒ fail-open (نفس فلسفة العميل — لا قفل على
      //   قيمة غريبة). الثغرة المسدودة: الطرد عند الإيقاف client-side فقط،
      //   وJWT الحساب الموقوف يبقى صالحاً فكان يستهلك السقف الشهري مباشرةً.
      const acctStatus = String(tr?.status ?? "");
      if (tr && (acctStatus === "new" || acctStatus === "rejected" || acctStatus === "suspended")) {
        return json(403, { error: "account_not_active" });
      }
      // M141 — بوابة الاشتراك: مصدرٌ واحد (tenant_access_level بالقاعدة). تجربةٌ منتهية
      // أو مدفوعٌ منتهٍ بلا سماح ⇒ 403 قبل أي نداء Anthropic (كان الحساب المنتهي
      // يستهلك الرصيد لأن خطة «تجريبي» تشمل الميزة). خطأ القراءة ⇒ fail-open.
      if (tr && acctStatus === "accepted") {
        const { data: lvl, error: lvlErr } = await admin.rpc("tenant_access_level", { p_uid: ownerId });
        if (!lvlErr && typeof lvl === "string" && lvl !== "full") {
          return json(403, { error: "subscription_inactive" });
        }
      }
      const aiOverride = (typeof tr?.ai_override === "boolean") ? tr.ai_override : null;
      if (aiOverride === false) return json(403, { error: "ai_override_off" });
      const planCode = (aiOverride === true) ? null : (tr?.plan || null);
      if (planCode) {
        const { data: pl } = await admin
          .from("subscription_plans")
          .select("entitlements")
          .eq("code", planCode)
          .maybeSingle();
        const ent = (pl?.entitlements && typeof pl.entitlements === "object") ? pl.entitlements : {};
        if (ent.ai_features === false) return json(403, { error: "ai_plan_not_included" });
        // Migration 132 — per-plan cap. Only a finite positive NUMBER counts;
        // strings/zero/negatives are ignored ⇒ fallback (never a free-for-all,
        // never an accidental lockout over a malformed catalog value).
        const rawCap = (ent as Record<string, unknown>).ai_monthly_calls;
        if (typeof rawCap === "number" && Number.isFinite(rawCap) && rawCap > 0) {
          planCallCap = Math.floor(rawCap);
        }
      }
    } catch (_e) { /* fail-open */ }
  }

  // ── 4) Usage caps (abuse + cost guards) ────────────────────────────
  //   4a. rolling-minute burst guard — tenants only (watch-point #70:
  //       an accepted account could fire its whole monthly quota in
  //       minutes; admin features are exempt to never throttle platform
  //       operations).
  //   4b. calendar-month cap — per-plan entitlements.ai_monthly_calls
  //       (Migration 132), MONTHLY_CALL_CAP as the legacy fallback.
  try {
    if (!isAdminFeature) {
      const minuteAgo = new Date(Date.now() - 60_000).toISOString();
      const { count: minuteCount } = await admin
        .from("ai_usage_log")
        .select("id", { count: "exact", head: true })
        .eq("owner_id", ownerId)
        .gte("created_at", minuteAgo);
      if ((minuteCount ?? 0) >= RATE_LIMIT_PER_MIN) return json(429, { error: "rate_limited" });
    }
    const monthStart = new Date();
    monthStart.setUTCDate(1); monthStart.setUTCHours(0, 0, 0, 0);
    const { count } = await admin
      .from("ai_usage_log")
      .select("id", { count: "exact", head: true })
      .eq("owner_id", ownerId)
      .gte("created_at", monthStart.toISOString());
    if ((count ?? 0) >= (planCallCap ?? MONTHLY_CALL_CAP)) return json(429, { error: "quota_exceeded" });
  } catch (_e) { /* a metering READ failure must not block the feature */ }

  // ── 5) Build the prompt (minimized · feature-specific) ─────────────
  let userContent = "";
  if (feature === "session_note") {
    const treatment = String(input?.treatment || "").slice(0, 400);
    const rough = String(input?.notes || "").slice(0, 1500);
    if (!treatment && !rough) return json(400, { error: "empty_input" });
    userContent =
      "العلاج المُسجَّل بالجلسة: " + (treatment || "(غير محدد)") + "\n" +
      "ملاحظات الطبيب المختصرة: " + (rough || "(لا يوجد)") + "\n\n" +
      "اكتب ملاحظة الجلسة السريرية.";
  } else if (feature === "patient_summary") {
    const alerts = String(input?.alerts || "").slice(0, 600);
    const allergies = String(input?.allergies || "").slice(0, 300);
    const record = String(input?.record || "").slice(0, 4000);
    const financials = String(input?.financials || "").slice(0, 800);
    if (!record && !alerts && !allergies) return json(400, { error: "empty_input" });
    userContent =
      "التنبيهات الطبية: " + (alerts || "(لا يوجد)") + "\n" +
      "الحساسية: " + (allergies || "(لا يوجد)") + "\n" +
      "الوضع المالي:\n" + (financials || "(لا يوجد)") + "\n" +
      "السجل السريري (الأحدث أولاً):\n" + (record || "(لا يوجد)") + "\n\n" +
      "لخّص ملف المريض للطبيب.";
  } else if (feature === "treatment_plan_explanation") {
    const plan = String(input?.plan || "").slice(0, 10000);
    if (!plan) return json(400, { error: "empty_input" });
    userContent =
      "خطة العلاج المقترحة (السن · نوع العلاج · التكلفة):\n" + plan + "\n\n" +
      "اشرح هذه الخطة للمريض بلغة بسيطة وواضحة.";
  } else if (feature === "followup_message") {
    // صفر-PII بالتصميم: أشهر انقطاع + بنود مراجعة (أسنان/علاجات بلا هوية)
    // + اسم العيادة. اسم المريض لا يصل هنا أبداً — {الاسم} يُستبدل client-side.
    const monthsAway = String(input?.months_away || "").slice(0, 20);
    const pendingItems = String(input?.pending_items || "").slice(0, 800);
    const clinicName = String(input?.clinic_name || "").slice(0, 120);
    if (!monthsAway && !pendingItems) return json(400, { error: "empty_input" });
    userContent =
      "مدة انقطاع المريض عن الزيارة بالأشهر: " + (monthsAway || "(غير معروفة)") + "\n" +
      "بنود المتابعة السنّية: " + (pendingItems || "(لا يوجد)") + "\n" +
      "اسم العيادة: " + (clinicName || "(غير محدد)") + "\n" +
      placeholderLine(sanitizePlaceholders(input?.placeholders)) + "\n" +
      "اكتب رسالة الاستدعاء.";
  } else if (feature === "whatsapp_draft") {
    // صفر-PII بالتصميم: قصد الطبيب نصاً + اسم العيادة فقط —
    // اسم المريض لا يصل هنا أبداً ({الاسم} يُستبدل client-side).
    const intent = String(input?.intent || "").slice(0, 600);
    const clinicName = String(input?.clinic_name || "").slice(0, 120);
    if (!intent) return json(400, { error: "empty_input" });
    const placeholders = sanitizePlaceholders(input?.placeholders);
    /* مفتاح مغلق داخل، جملة ثابتة من الخادم خارج — صفر نص عميل هنا */
    const surface = pick(DRAFT_CONTEXTS, input?.context);
    userContent =
      "قصد الطبيب: " + intent + "\n" +
      "اسم العيادة: " + (clinicName || "(غير محدد)") + "\n" +
      (surface ? surface + "\n" : "") +
      placeholderLine(placeholders) + "\n" +
      "اكتب الرسالة.";
  } else if (feature === "monthly_digest") {
    // صفر-PII بالكامل: أرقام مجمّعة + أسماء علاجات من كتالوج العيادة —
    // لا اسم مريض ولا طبيب ولا معرّف. الأرقام تصل **منسّقة مسبقاً** بنفس
    // دوال العرض (fmtSY/fmtPct) فيستحيل أن يخالف الملخّص ما تعرضه البطاقات.
    // 🔒 قراءة فقط — هذه الميزة لا تكتب في أي جدول مالي.
    const facts = String(input?.facts || "").slice(0, 4000);
    if (!facts) return json(400, { error: "empty_input" });
    userContent =
      "أرقام الفترة (محسوبة ومنسّقة مسبقاً — انسخها كما هي ولا تعد حسابها):\n" +
      facts + "\n\n" +
      "اكتب ملخّص الفترة.";
  } else if (feature === "postop_instructions") {
    // صفر-PII بالكامل: اسم نوع العلاج فقط — لا مريض ولا هوية
    // (النص وثيقة عامة تُحفَظ كتعليمات/قالب ويُعاد استخدامها).
    const treatment = String(input?.treatment || "").slice(0, 200);
    if (!treatment) return json(400, { error: "empty_input" });
    // تلميح اختياري من الطبيب (الموجة 2 — امتداد معتمد): يُدمج بالمدخل فقط،
    // وقواعد البرومبت (منع الأدوية/الجرعات) سيّدة عليه صراحةً.
    const hints = String(input?.hints || "").slice(0, 300);
    userContent =
      "نوع العلاج: " + treatment + "\n" +
      (hints ? "توجيهات إضافية من الطبيب: " + hints + "\n" : "") +
      "\n" + "اكتب تعليمات ما بعد العلاج.";
  } else if (feature === "referral_report") {
    // الموجة 2 بند #1 — صفر-PII بالتصميم: نوع المستند مفتاح مغلق (سياقه
    // جملة ثابتة من الخادم عبر pick) + سبب الطبيب + بنود سريرية مجرّدة +
    // تنبيهات كأصناف + اسم العيادة. اسم المريض لا يصل هنا أبداً —
    // {الاسم}/{التاريخ} يُستبدلان client-side بعد التوليد وقبل أن يظهر
    // النص للطبيب بالمودال. 🔒 قراءة فقط — صفر كتابة بأي جدول.
    const docCtx = pick(REFERRAL_DOC_TYPES, input?.doc_type);
    if (!docCtx) return json(400, { error: "empty_input" });
    const reason = String(input?.reason || "").slice(0, 600);
    const teeth = String(input?.teeth || "").slice(0, 100);
    const treatments = String(input?.treatments || "").slice(0, 2000);
    const alerts = String(input?.alerts || "").slice(0, 600);
    const clinicName = String(input?.clinic_name || "").slice(0, 120);
    if (!reason && !treatments) return json(400, { error: "empty_input" });
    const recipient = String(input?.recipient || "").slice(0, 120);
    // اختصاص الجهة المحوَّل إليها (اختياري) — يُذكر حرفياً إن ورد فقط،
    // والبرومبت يمنع استنتاجه منعاً باتاً (ملاحظة live test: كان يُخترع).
    const recipientSpec = String(input?.recipient_specialty || "").slice(0, 120);
    const expCtx = pick(REFERRAL_EXPECTATIONS, input?.expectation) ||
      "المطلوب من الزميل: تقييم الحالة وإبداء الرأي (لم يحدِّد الطبيب خياراً — صياغة عامة).";
    const urgCtx = pick(REFERRAL_URGENCY, input?.urgency);   // routine/مجهول = لا سطر
    userContent =
      docCtx + "\n" +
      "الجهة أو الطبيب المحوَّل إليه: " + (recipient || "(غير محدد — مخاطبة عامة بلا اختصاص)") + "\n" +
      (recipientSpec ? "اختصاص الجهة المحوَّل إليها: " + recipientSpec + "\n" : "") +
      (urgCtx ? urgCtx + "\n" : "") +
      expCtx + "\n" +
      "سبب الكتاب بكلمات الطبيب: " + (reason || "(غير محدد)") + "\n" +
      "الأسنان موضوع الكتاب: " + (teeth || "(لم تُحدَّد — التزم بما ورد في السبب)") + "\n" +
      "الخلفية السريرية (سوابق العلاج — للسياق فقط، ليست موضوع الكتاب):\n" + (treatments || "(لا يوجد)") + "\n" +
      "التنبيهات الطبية والحساسية: " + (alerts || "(لا يوجد)") + "\n" +
      "اسم العيادة: " + (clinicName || "(غير محدد)") + "\n\n" +
      "اكتب المستند.";
  } else if (feature === "daily_digest") {
    // الموجة 2 بند #3 — صفر-PII بالكامل: أرقام اليوم مجمّعة كما تعرضها لوحة
    // العيادة حرفياً (تُقرأ من عناصر العرض نفسها client-side) + جدول الغد
    // عدداً وأوقاتاً — لا اسم مريض ولا طبيب ولا معرّف. الأرقام تصل
    // **منسّقة مسبقاً** فيستحيل أن يخالف الملخّص ما على الشاشة، والبرومبت
    // ممنوع من أي حساب (نمط monthly_digest حرفياً).
    // 🔒 قراءة عرض فقط — صفر كتابة بأي جدول.
    const facts = String(input?.facts || "").slice(0, 2500);
    if (!facts) return json(400, { error: "empty_input" });
    userContent =
      "أرقام اليوم وجدول الغد (محسوبة ومنسّقة مسبقاً — انسخها كما هي ولا تعد حسابها):\n" +
      facts + "\n\n" +
      "اكتب ملخّص نهاية اليوم.";
  } else if (feature === "preop_instructions") {
    // الموجة 2 بند #4 — مرآة postop_instructions حرفياً: صفر-PII بالكامل،
    // اسم نوع العلاج فقط — لا مريض ولا هوية (النص وثيقة تحضير عامة).
    const treatment = String(input?.treatment || "").slice(0, 200);
    if (!treatment) return json(400, { error: "empty_input" });
    const hints = String(input?.hints || "").slice(0, 300);
    userContent =
      "نوع العلاج: " + treatment + "\n" +
      (hints ? "توجيهات إضافية من الطبيب: " + hints + "\n" : "") +
      "\n" + "اكتب تعليمات ما قبل العلاج (التحضير للموعد).";
  } else if (feature === "treatment_sequencing") {
    // الموجة 2 بند #7 — نفس حمولة شرح الخطة حرفياً (بنود مجمّعة deterministic
    // بالعميل، صفر PII). الجمهور الطبيب: اقتراح ترتيب لما سجّله هو حصراً —
    // البرومبت ممنوع من إضافة/حذف/تشخيص، والإنسان في الحلقة مطلق (عرض عابر
    // غير محفوظ). 🔒 قراءة فقط — صفر كتابة بأي جدول.
    const plan = String(input?.plan || "").slice(0, 10000);
    if (!plan) return json(400, { error: "empty_input" });
    userContent =
      "بنود خطة العلاج المسجّلة (مجمّعة مسبقاً):\n" + plan + "\n\n" +
      "اقترح ترتيب تنفيذ البنود على مراحل.";
  } else if (feature === "patient_reply_draft") {
    // الموجة 2 بند #5 — صفر-PII من المنصة: سؤال المريض نصٌّ يلصقه الطبيب
    // بمسؤوليته (سابقة intent ببند whatsapp_draft حرفياً) + توجيه اختياري
    // + اسم العيادة + القائمة البيضاء للعناصر النائبة. اسم المريض لا يصل
    // هنا أبداً ({الاسم} يُحلّ client-side بمسار ppWaResolve القائم).
    // 🔒 قراءة فقط — صفر كتابة بأي جدول.
    const question = String(input?.question || "").slice(0, 800);
    if (!question) return json(400, { error: "empty_input" });
    const intent = String(input?.intent || "").slice(0, 300);
    const clinicName = String(input?.clinic_name || "").slice(0, 120);
    const placeholders = sanitizePlaceholders(input?.placeholders);
    userContent =
      "سؤال المريض كما وصل: " + question + "\n" +
      (intent ? "توجيه الطبيب للرد: " + intent + "\n" : "") +
      "اسم العيادة: " + (clinicName || "(غير محدد)") + "\n" +
      placeholderLine(placeholders) + "\n" +
      "اكتب الرد.";
  } else if (feature === "lab_order_draft") {
    // الموجة 2 بند #6 (ج2) — صفر-PII بالكامل: نوع العمل + رقم السن + اللون
    // + تاريخ التسليم + اسم العيادة + كلمات الطبيب الخام. لا اسم مريض ولا
    // مخبر ولا معرّف — ({الاسم}/{التاريخ} يُستبدلان client-side بنمط #372،
    // والإرسال للمخبر واتساباً يجري بالمتصفح بضغطة الطبيب حصراً).
    // 🔒 قراءة فقط — صفر كتابة بأي جدول، والتكلفة لا تصل هنا أصلاً.
    const workType = String(input?.work_type || "").slice(0, 200);
    if (!workType) return json(400, { error: "empty_input" });
    const tooth = String(input?.tooth || "").slice(0, 120);
    const shade = String(input?.shade || "").slice(0, 100);
    const rawNotes = String(input?.notes || "").slice(0, 600);
    const dueDate = String(input?.due_date || "").slice(0, 20);
    const clinicName = String(input?.clinic_name || "").slice(0, 120);
    userContent =
      "نوع العمل: " + workType + "\n" +
      (tooth ? "رقم السن: " + tooth + "\n" : "") +
      (shade ? "اللون: " + shade + "\n" : "") +
      (dueDate ? "تاريخ التسليم المطلوب: " + dueDate + "\n" : "") +
      (clinicName ? "اسم العيادة: " + clinicName + "\n" : "") +
      (rawNotes ? "كلمات الطبيب (مادة/تصميم/ملاحظات): " + rawNotes + "\n" : "") +
      "اكتب أمر العمل المخبري.";
  } else if (feature === "health_content") {
    // الموجة 2 بند #8 — أنظف بند بالمنظومة: صفر بيانات مرضى بنيوياً.
    // الحمولة موضوعٌ عام + منصة + نبرة + اسم العيادة فقط؛ لا يوجد بهذا
    // الفرع أي حقل مريض ولا معرّف ولا حالة، ولا استعلام قاعدة بيانات.
    // 🔒 قراءة فقط — صفر كتابة بأي جدول.
    const topic = String(input?.topic || "").slice(0, 120);
    if (!topic) return json(400, { error: "empty_input" });
    const platform = String(input?.platform || "").slice(0, 40);
    const tone = String(input?.tone || "").slice(0, 40);
    const clinicName = String(input?.clinic_name || "").slice(0, 120);
    userContent =
      "موضوع المنشور: " + topic + "\n" +
      (platform ? "المنصة المستهدفة: " + platform + "\n" : "") +
      (tone ? "النبرة المطلوبة: " + tone + "\n" : "") +
      (clinicName ? "اسم العيادة: " + clinicName + "\n" : "") +
      "اكتب المنشور التوعوي.";
  } else if (feature === "tenant_health_narrative") {
    // الموجة 2 بند #9 — سطح أدمن: مؤشّرات اشتراك حساب واحد، **لا بيانات
    // عيادة ولا مريض ولا هوية**. الحمولة مفتاح واحد لا غير (نمط
    // daily_digest حرفياً): نصّ مجمَّع محسوب ومنسَّق client-side من نفس
    // الدوال التي ترسم درج العميل — فيستحيل أن يخالف السردُ الشاشةَ،
    // والنموذج ممنوع من أي حساب أو مقارنة أو تنبّؤ.
    // 🔒 قراءة عرض فقط — صفر كتابة بأي جدول.
    const facts = String(input?.facts || "").slice(0, 2000);
    if (!facts) return json(400, { error: "empty_input" });
    userContent =
      "مؤشّرات حساب العميل (محسوبة ومنسّقة مسبقاً — انسخها كما هي ولا تعد حسابها):\n" +
      facts + "\n\n" +
      "اكتب قراءة خطر الانسحاب لهذا الحساب.";
  } else if (feature === "nl_analytics") {
    // الموجة 2 بند #10 — استعلام بلغة طبيعية: النموذج مصنّف نوايا فقط.
    // لا SQL ولا استخراج قيم ولا صياغة جواب — يعيد مفتاح صنفٍ واحداً من
    // قائمة مغلقة (صفر رقم بمخرجه بالتصميم — درس #410/#413)، والاستخراج
    // والتنفيذ والصياغة كلها حتمية بالعميل بمحرّكات العرض القانونية ذاتها.
    // الأسماء تصل معتَّمة {اسم} سلفاً (تعتيم حتمي بالعميل قبل الإرسال).
    // 🔒 قراءة عرض فقط — صفر كتابة بأي جدول.
    const question = String(input?.question || "").slice(0, 300);
    if (!question.trim()) return json(400, { error: "empty_input" });
    userContent = "سؤال الطبيب:\n" + question + "\n\nأخرج مفتاح الصنف وحده.";
  }

  // ── 6) Call Anthropic (server-side · key never leaves here) ────────
  // سقف الميزة، ومحاولة ثانية بسقف مضاعف إن انقطع الناتج (stop_reason=max_tokens)
  // كي لا يصل المريض شرحٌ مبتور تسقط منه علاجات بصمت.
  let aiText = "";
  let usage = { input_tokens: 0, output_tokens: 0 };
  let tokenCap = (hasFeature(FEATURE_MAX_TOKENS, feature) ? FEATURE_MAX_TOKENS[feature] : 0) || MAX_TOKENS;
  try {
    let r: Response | null = null;
    for (let attempt = 0; attempt < 2; attempt++) {
      r = await fetch("https://api.anthropic.com/v1/messages", {
        method: "POST",
        headers: {
          "content-type": "application/json",
          "x-api-key": ANTHROPIC_API_KEY,
          "anthropic-version": ANTHROPIC_VERSION,
        },
        body: JSON.stringify({
          model: AI_MODEL,
          max_tokens: tokenCap,
          system: SYSTEM_PROMPTS[feature],
          messages: [{ role: "user", content: userContent }],
        }),
      });
      if (!r.ok) break;
      const peek = await r.clone().json();
      if (peek?.stop_reason === "max_tokens" && attempt === 0) {
        console.warn("ai_truncated_retry", feature, tokenCap);
        tokenCap = tokenCap * 2;
        continue;
      }
      break;
    }
    if (!r) return json(502, { error: "ai_unavailable" });
    if (!r.ok) {
      const errTxt = await r.text().catch(() => "");
      console.error("anthropic_error", r.status, errTxt.slice(0, 300));
      return json(502, { error: "ai_upstream_error" });
    }
    const data = await r.json();
    aiText = (Array.isArray(data?.content) ? data.content : [])
      .filter((b: any) => b?.type === "text")
      .map((b: any) => b.text)
      .join("\n")
      .trim();
    usage = {
      input_tokens: data?.usage?.input_tokens ?? 0,
      output_tokens: data?.usage?.output_tokens ?? 0,
    };
  } catch (e) {
    console.error("anthropic_fetch_failed", String(e));
    return json(502, { error: "ai_upstream_error" });
  }
  if (!aiText) return json(502, { error: "ai_empty_response" });

  // ── 7) Meter usage (NON-FATAL — a write failure never breaks UX) ───
  try {
    await admin.from("ai_usage_log").insert({
      owner_id: ownerId,
      feature,
      model: AI_MODEL,
      input_tokens: usage.input_tokens,
      output_tokens: usage.output_tokens,
    });
  } catch (_e) { /* best-effort metering */ }

  return json(200, { text: aiText });
});
