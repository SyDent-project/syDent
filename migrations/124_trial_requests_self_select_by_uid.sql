-- Migration 124: قراءة المستأجر لصفّه بـuser_id (شرط مُسبق لقسم «معلومات الدخول»)
--
-- المشكلة (مُشخَّصة حيّاً، فخّ كامن لم ينفجر بعد): سياسة القراءة الوحيدة على
-- trial_requests هي «User read own trial» بشرط:
--     email = auth.jwt() ->> 'email'
-- أي أنها تربط حقّ القراءة بتطابق **نصّي** بين عمود جدولٍ ثابت وبين البريد
-- داخل التوكن الحيّ. وsettings.html تغيّر البريد بـauth.updateUser({email})
-- ولا تلمس trial_requests.email إطلاقاً (ولا تستطيع: لا سياسة UPDATE للمستأجر
-- على هذا الجدول أصلاً). فبمجرّد أن يؤكّد طبيبٌ بريده الجديد، ينحرف العمودان
-- ويسقط الشرط ⇒ **يفقد الطبيب قراءة صفّه هو**، ومعه أي واجهة تعتمد عليه.
--
-- تحقّق حيّ قبل الكتابة: 8 صفوف من 8 لا يزال tr.email = auth.users.email
-- (لم يستعمل أحدٌ زرّ تغيير البريد بعد) — أي أن العطب مؤجَّل لا منتفٍ، وأول
-- مستفيد من الميزة الجديدة هو أول ضحية له.
--
-- الحل — سياسة ثانية **إضافية** (PERMISSIVE ⇒ تُجمَع بـOR مع القائمة):
--     user_id = auth.uid()
-- ربطٌ بالمفتاح الحقيقي بدل التطابق النصّي. لا تُحذف السياسة القديمة ولا
-- تُعدَّل: صفوفٌ قديمة قد يكون user_id فيها NULL (طلب أُنشئ قبل ربط الحساب)
-- وتبقى مقروءةً بالبريد كما كانت. الأثر صافي = توسيعُ القراءة إلى صفّ المستخدم
-- نفسه لا غير.
--
-- النطاق: SELECT فقط. لا INSERT ولا UPDATE ولا DELETE، ولا مساس بسياسة
-- الأدمن (is_platform_admin) ولا بأي جدول مالي.
--
-- مطبَّقة حيّاً عبر MCP ومؤكَّدة بالاستعلامات في 4 آب 2026.

BEGIN;

DROP POLICY IF EXISTS trial_requests_self_select_by_uid ON public.trial_requests;

CREATE POLICY trial_requests_self_select_by_uid
  ON public.trial_requests
  FOR SELECT
  TO authenticated
  USING (user_id = auth.uid());

COMMIT;
